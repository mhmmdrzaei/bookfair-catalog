create or replace function public.claim_pending_org_invites(invited_email text default null)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  pending_email text;
  claimed_count integer := 0;
  invite_row record;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  pending_email := lower(coalesce(invited_email, auth.jwt()->>'email', ''));
  if pending_email = '' then
    return 0;
  end if;

  for invite_row in
    select id, organization_id
    from public.organization_invites
    where accepted_at is null
      and lower(email) = pending_email
  loop
    insert into public.organization_members (organization_id, user_id, role)
    values (invite_row.organization_id, auth.uid(), 'member')
    on conflict (organization_id, user_id) do nothing;

    update public.organization_invites
    set accepted_at = now()
    where id = invite_row.id;

    claimed_count := claimed_count + 1;
  end loop;

  return claimed_count;
end;
$$;

create or replace function public.adjust_inventory_stock(
  org_id uuid,
  inventory_item_id uuid,
  change_delta integer,
  change_note text default ''
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  current_quantity integer;
  next_quantity integer;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if not public.is_org_member(org_id) then
    raise exception 'Not authorized for this organization';
  end if;

  select quantity
  into current_quantity
  from public.inventory_items
  where id = inventory_item_id
    and organization_id = org_id
  for update;

  if current_quantity is null then
    raise exception 'Item not found';
  end if;

  next_quantity := current_quantity + change_delta;
  if next_quantity < 0 then
    raise exception 'Stock cannot go below zero';
  end if;

  update public.inventory_items
  set quantity = next_quantity
  where id = inventory_item_id
    and organization_id = org_id;

  insert into public.stock_movements (
    organization_id,
    item_id,
    delta,
    note,
    created_by
  )
  values (
    org_id,
    inventory_item_id,
    change_delta,
    coalesce(change_note, ''),
    auth.uid()
  );

  return next_quantity;
end;
$$;

create or replace function public.record_inventory_sale(
  org_id uuid,
  inventory_item_id uuid,
  sale_payment_method text,
  sale_account text default '',
  sale_amount_override numeric default null,
  sale_quantity integer default 1
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  current_price numeric(10, 2);
  current_quantity integer;
  next_quantity integer;
  sale_amount numeric(10, 2);
  sale_note text;
  resolved_account_id uuid;
  new_group_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if not public.is_org_member(org_id) then
    raise exception 'Not authorized for this organization';
  end if;

  if sale_quantity < 1 then
    raise exception 'Sale quantity must be at least 1';
  end if;

  if sale_payment_method not in ('Venmo', 'Zelle', 'Cash', 'Other') then
    raise exception 'Invalid payment method';
  end if;

  select price, quantity
  into current_price, current_quantity
  from public.inventory_items
  where id = inventory_item_id
    and organization_id = org_id
  for update;

  if current_quantity is null then
    raise exception 'Item not found';
  end if;

  if current_quantity < sale_quantity then
    raise exception 'Not enough stock to record this sale';
  end if;

  sale_amount := coalesce(sale_amount_override, current_price * sale_quantity);
  if sale_amount < 0 then
    raise exception 'Sale amount must be positive';
  end if;

  resolved_account_id := public.ensure_org_account(org_id, sale_account);

  sale_note := 'Sale: ' || sale_payment_method;
  if coalesce(trim(sale_account), '') <> '' then
    sale_note := sale_note || ', Account: ' || sale_account;
  end if;
  if sale_amount_override is not null then
    sale_note := sale_note || ', OR Price: $' || trim(to_char(sale_amount_override, 'FM999999990.00'));
  end if;

  next_quantity := current_quantity - sale_quantity;

  insert into public.sale_groups (
    organization_id,
    payment_method,
    account_id,
    account_snapshot,
    total_amount,
    created_by
  )
  values (
    org_id,
    sale_payment_method,
    resolved_account_id,
    coalesce(btrim(sale_account), ''),
    sale_amount,
    auth.uid()
  )
  returning id into new_group_id;

  insert into public.sales (
    organization_id,
    sale_group_id,
    item_id,
    payment_method,
    account_id,
    account,
    amount,
    quantity,
    created_by
  )
  values (
    org_id,
    new_group_id,
    inventory_item_id,
    sale_payment_method,
    resolved_account_id,
    coalesce(sale_account, ''),
    sale_amount,
    sale_quantity,
    auth.uid()
  );

  update public.inventory_items
  set quantity = next_quantity
  where id = inventory_item_id
    and organization_id = org_id;

  insert into public.stock_movements (
    organization_id,
    item_id,
    delta,
    note,
    created_by
  )
  values (
    org_id,
    inventory_item_id,
    sale_quantity * -1,
    sale_note,
    auth.uid()
  );

  return next_quantity;
end;
$$;

create or replace function public.record_multi_item_sale(
  org_id uuid,
  sale_payment_method text,
  sale_account text default '',
  sale_lines jsonb default '[]'::jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  line_item record;
  current_price numeric(10, 2);
  current_quantity integer;
  sale_total numeric(10, 2) := 0;
  resolved_account_id uuid;
  new_group_id uuid;
  requested_quantity integer;
  sale_note text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if not public.is_org_member(org_id) then
    raise exception 'Not authorized for this organization';
  end if;

  if sale_payment_method not in ('Venmo', 'Zelle', 'Cash', 'Other') then
    raise exception 'Invalid payment method';
  end if;

  if jsonb_typeof(sale_lines) <> 'array' or jsonb_array_length(sale_lines) = 0 then
    raise exception 'At least one item is required';
  end if;

  resolved_account_id := public.ensure_org_account(org_id, sale_account);

  for line_item in
    select
      (value->>'itemId')::uuid as item_id,
      greatest(1, coalesce((value->>'quantity')::integer, 0)) as quantity
    from jsonb_array_elements(sale_lines)
  loop
    requested_quantity := line_item.quantity;

    select price, quantity
    into current_price, current_quantity
    from public.inventory_items
    where id = line_item.item_id
      and organization_id = org_id
    for update;

    if current_quantity is null then
      raise exception 'Item not found in multi-sell';
    end if;

    if current_quantity < requested_quantity then
      raise exception 'Not enough stock for one of the selected items';
    end if;

    sale_total := sale_total + (current_price * requested_quantity);
  end loop;

  insert into public.sale_groups (
    organization_id,
    payment_method,
    account_id,
    account_snapshot,
    total_amount,
    created_by
  )
  values (
    org_id,
    sale_payment_method,
    resolved_account_id,
    coalesce(btrim(sale_account), ''),
    sale_total,
    auth.uid()
  )
  returning id into new_group_id;

  for line_item in
    select
      (value->>'itemId')::uuid as item_id,
      greatest(1, coalesce((value->>'quantity')::integer, 0)) as quantity
    from jsonb_array_elements(sale_lines)
  loop
    requested_quantity := line_item.quantity;

    select price, quantity
    into current_price, current_quantity
    from public.inventory_items
    where id = line_item.item_id
      and organization_id = org_id
    for update;

    update public.inventory_items
    set quantity = current_quantity - requested_quantity
    where id = line_item.item_id
      and organization_id = org_id;

    insert into public.sales (
      organization_id,
      sale_group_id,
      item_id,
      payment_method,
      account_id,
      account,
      amount,
      quantity,
      created_by
    )
    values (
      org_id,
      new_group_id,
      line_item.item_id,
      sale_payment_method,
      resolved_account_id,
      coalesce(sale_account, ''),
      current_price * requested_quantity,
      requested_quantity,
      auth.uid()
    );

    sale_note := 'Sale: ' || sale_payment_method;
    if coalesce(trim(sale_account), '') <> '' then
      sale_note := sale_note || ', Account: ' || sale_account;
    end if;

    insert into public.stock_movements (
      organization_id,
      item_id,
      delta,
      note,
      created_by
    )
    values (
      org_id,
      line_item.item_id,
      requested_quantity * -1,
      sale_note,
      auth.uid()
    );
  end loop;

  return new_group_id;
end;
$$;

create or replace function public.record_account_transfer(
  org_id uuid,
  from_account_name text,
  to_account_name text,
  transfer_payment_method text,
  transfer_amount numeric,
  transfer_note text default ''
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  from_account_id uuid;
  to_account_id uuid;
  transfer_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if not public.is_org_member(org_id) then
    raise exception 'Not authorized for this organization';
  end if;

  if transfer_amount <= 0 then
    raise exception 'Transfer amount must be positive';
  end if;

  if transfer_payment_method not in ('Venmo', 'Zelle', 'Cash', 'Other') then
    raise exception 'Invalid payment method';
  end if;

  if btrim(coalesce(from_account_name, '')) = '' or btrim(coalesce(to_account_name, '')) = '' then
    raise exception 'Both accounts are required';
  end if;

  from_account_id := public.ensure_org_account(org_id, from_account_name);
  to_account_id := public.ensure_org_account(org_id, to_account_name);

  insert into public.account_transfers (
    organization_id,
    from_account_id,
    from_account_snapshot,
    to_account_id,
    to_account_snapshot,
    payment_method,
    amount,
    note,
    created_by
  )
  values (
    org_id,
    from_account_id,
    btrim(from_account_name),
    to_account_id,
    btrim(to_account_name),
    transfer_payment_method,
    transfer_amount,
    coalesce(transfer_note, ''),
    auth.uid()
  )
  returning id into transfer_id;

  return transfer_id;
end;
$$;

