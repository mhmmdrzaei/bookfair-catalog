drop policy if exists "authenticated users can read item images" on storage.objects;
create policy "authenticated users can read item images"
  on storage.objects
  for select
  using (bucket_id = 'item-images' and auth.role() = 'authenticated');

drop policy if exists "authenticated users can upload item images" on storage.objects;
create policy "authenticated users can upload item images"
  on storage.objects
  for insert
  with check (bucket_id = 'item-images' and auth.role() = 'authenticated');

drop policy if exists "authenticated users can update item images" on storage.objects;
create policy "authenticated users can update item images"
  on storage.objects
  for update
  using (bucket_id = 'item-images' and auth.role() = 'authenticated')
  with check (bucket_id = 'item-images' and auth.role() = 'authenticated');

drop policy if exists "authenticated users can delete item images" on storage.objects;
create policy "authenticated users can delete item images"
  on storage.objects
  for delete
  using (bucket_id = 'item-images' and auth.role() = 'authenticated');
